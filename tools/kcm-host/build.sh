#!/bin/sh
# Build kcmtool: the Android 16 AOSP KeyCharacterMap parser compiled for the host.
#
# KeyCharacterMap.cpp and Tokenizer.cpp are compiled unmodified from the pinned tag.
# Headers that would pull in binder/libbase/libui are replaced by minimal shims in
# shim/; those shims only satisfy the parts of KeyCharacterMap.cpp that the parser
# and key-behavior lookup never execute (Parcel, KeyEvent synthesis).
# The keycode label table and the meta-state helpers are generated from the same tag.
# AOSP sources (Apache-2.0) are downloaded into aosp/<tag>/ and are not committed; the
# stock keyboard maps fetched alongside them serve as real-world parser test inputs.
set -eu
TAG=${AOSP_TAG:-android-16.0.0_r1}
HERE=$(cd "$(dirname "$0")" && pwd)
SRC="$HERE/aosp/$TAG"
OUT=${1:-$HERE/kcmtool}

fetch() { # repo path dest
    [ -s "$3" ] && return 0
    mkdir -p "$(dirname "$3")"
    # Download and decode as separate steps: POSIX sh has no pipefail, so a failed curl in a
    # pipe would leave an empty file that later runs treat as already fetched.
    curl -fsS --max-time 60 -o "$3.b64" \
        "https://android.googlesource.com/platform/$1/+/refs/tags/$TAG/$2?format=TEXT"
    base64 -d "$3.b64" > "$3.tmp"
    [ -s "$3.tmp" ] || { echo "empty download: $1 $2" >&2; exit 1; }
    rm "$3.b64"
    mv "$3.tmp" "$3"
}

fetch frameworks/native libs/input/KeyCharacterMap.cpp "$SRC/KeyCharacterMap.cpp"
fetch frameworks/native include/input/KeyCharacterMap.h "$SRC/include/input/KeyCharacterMap.h"
fetch frameworks/native include/android/input.h "$SRC/include/android/input.h"
fetch frameworks/native include/android/keycodes.h "$SRC/include/android/keycodes.h"
fetch frameworks/native libs/input/InputEventLabels.cpp "$SRC/InputEventLabels.cpp"
fetch frameworks/native libs/input/Keyboard.cpp "$SRC/Keyboard.cpp"
fetch system/core libutils/Tokenizer.cpp "$SRC/Tokenizer.cpp"
fetch system/core libutils/include/utils/Tokenizer.h "$SRC/include/utils/Tokenizer.h"
fetch system/core libutils/binder/include/utils/Errors.h "$SRC/include/utils/Errors.h"
fetch frameworks/native libs/input/KeyLayoutMap.cpp "$SRC/KeyLayoutMap.cpp"
fetch frameworks/native include/input/KeyLayoutMap.h "$SRC/include/input/KeyLayoutMap.h"
# Input.h itself pulls in binder and more; only its LED and policy flag enums are extracted below.
fetch frameworks/native include/input/Input.h "$SRC/Input.h.txt"
fetch frameworks/base data/keyboards/Generic.kl "$SRC/keyboards/Generic.kl"
for kcm in Generic Virtual; do
    fetch frameworks/base "data/keyboards/$kcm.kcm" "$SRC/keyboards/$kcm.kcm"
done

# Key code labels accepted by the AOSP parser, one per line; src/keycodes.txt must equal this.
grep -oE 'DEFINE_KEYCODE\([A-Z0-9_]+\)' "$SRC/InputEventLabels.cpp" \
    | sed 's/^DEFINE_KEYCODE(\(.*\))$/\1/' > "$SRC/keycodes.txt"

# LED and policy flag constants of input/Input.h, which the shim Input.h includes.
{
    echo '// Generated by build.sh from' "$TAG" 'include/input/Input.h - do not edit.'
    echo '#pragma once'
    echo 'namespace android { enum {'
    grep -E '^\s*ALED_[A-Z0-9_]+ = 0x[0-9a-f]+,' "$SRC/Input.h.txt"
    grep -E '^\s*POLICY_FLAG_[A-Z_]+ = 0x[0-9a-f]+,' "$SRC/Input.h.txt"
    echo '}; }'
} > "$SRC/include/input_constants.h"
grep -q POLICY_FLAG_FUNCTION "$SRC/include/input_constants.h" || { echo 'Input.h constant extraction failed' >&2; exit 1; }

GEN="$SRC/aosp_extract.cpp"
{
    echo '// Generated by build.sh from' "$TAG" '- do not edit.'
    echo '#include <android/keycodes.h>'
    echo '#include <android/input.h>'
    echo '#include <input/Keyboard.h>'
    echo '#include <input/InputEventLabels.h>'
    echo '#include <input/Input.h>'
    echo '#include <string>'
    echo '#include <unordered_map>'
    echo 'namespace android {'
    echo '#define DEFINE_KEYCODE(key) { #key, AKEYCODE_##key }'
    echo 'static const std::unordered_map<std::string, int> KEYCODES = {'
    grep -oE 'DEFINE_KEYCODE\([A-Z0-9_]+\)' "$SRC/InputEventLabels.cpp" | sed 's/$/,/'
    echo '};'
    echo 'std::optional<int> InputEventLookup::getKeyCodeByLabel(const char* l) {'
    echo '    auto it = KEYCODES.find(l);'
    echo '    if (it == KEYCODES.end()) return std::nullopt;'
    echo '    return it->second;'
    echo '}'
    echo '#define DEFINE_AXIS(axis) { #axis, AMOTION_EVENT_AXIS_##axis }'
    echo '#define DEFINE_LED(led) { #led, ALED_##led }'
    echo '#define DEFINE_FLAG(flag) { #flag, POLICY_FLAG_##flag }'
    for kind in AXIS LED FLAG; do
        echo "static const std::unordered_map<std::string, int> TABLE_$kind = {"
        grep -oE "DEFINE_$kind\\([A-Z0-9_]+\\)" "$SRC/InputEventLabels.cpp" | sed 's/$/,/'
        echo '};'
    done
    echo 'static std::optional<int> lookup(const std::unordered_map<std::string, int>& t, const char* l) {'
    echo '    auto it = t.find(l);'
    echo '    if (it == t.end()) return std::nullopt;'
    echo '    return it->second;'
    echo '}'
    echo 'std::optional<int> InputEventLookup::getKeyFlagByLabel(const char* l) { return lookup(TABLE_FLAG, l); }'
    echo 'std::optional<int> InputEventLookup::getAxisByLabel(const char* l) { return lookup(TABLE_AXIS, l); }'
    echo 'std::optional<int> InputEventLookup::getLedByLabel(const char* l) { return lookup(TABLE_LED, l); }'
    echo '}'
    echo 'const char* kcmtoolKeyLabel(int keyCode) {'
    echo '    static const std::unordered_map<int, const char*> LABELS = [] {'
    echo '        std::unordered_map<int, const char*> m;'
    echo '        for (const auto& [label, code] : android::KEYCODES) m.emplace(code, label.c_str());'
    echo '        return m;'
    echo '    }();'
    echo '    auto it = LABELS.find(keyCode);'
    echo '    return it == LABELS.end() ? nullptr : it->second;'
    echo '}'
    echo 'namespace android {'
    # setEphemeralMetaState .. updateMetaState, verbatim.
    awk '/^static int32_t setEphemeralMetaState/,/^bool isMetaKey/' "$SRC/Keyboard.cpp" | sed '$d'
    echo '}'
} > "$GEN"
grep -q '^int32_t updateMetaState' "$GEN" || { echo 'meta-state extraction failed' >&2; exit 1; }

CXX="g++ -std=c++20 -O1 -w -I$HERE/shim -I$SRC/include"
$CXX -DLOG_TAG='"kcm"' -o "$OUT" "$HERE/main.cpp" "$SRC/KeyCharacterMap.cpp" "$SRC/Tokenizer.cpp" "$GEN"
$CXX -DLOG_TAG='"kl"' -o "$(dirname "$OUT")/kltool" "$HERE/kltool.cpp" "$SRC/KeyLayoutMap.cpp" "$SRC/Tokenizer.cpp" "$GEN"
echo "built $OUT and kltool ($TAG)"
